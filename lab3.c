#include <stdio.h>
#include <math.h>

int main() {
    // Массив аргументов X
    double X[] = {1.0, 0.5, 0.25, 0.125, 0.0625, 0.03125, 0.015625};
    int n = sizeof(X) / sizeof(X[0]);

    // Печать заголовка таблицы
    printf("=================================================================================================================\n");
    printf("%-10s | %-12s | %-15s | %-15s | %-12s | %-12s\n", 
           "X", "f(X) точн.", "f(X) скоб.", "f(X) прям.", "Абс. ошиб.", "Относ. ошиб.");
    printf("=================================================================================================================\n");

    // Цикл по всем значениям аргумента X
    for (int i = 0; i < n; i++) {
        double x = X[i];

        // а) Точное значение функции
        double f_exact = sqrt(1.0 + x);

        // б) Приближенное значение с использованием скобочной формы (схема Горнера)
        // Формула: 1 + X/2 - X^2/8 + 3X^3/48 - 15X^4/384
        // В скобочном виде: 1 + x * (1/2.0 + x * (-1/8.0 + x * (3/48.0 + x * (-15/384.0))))
        double f_approx_bracket = 1.0 + x * (0.5 + x * (-0.125 + x * (0.0625 + x * (-15.0 / 384.0))));

        // в) Приближенное значение «в лоб» без скобочных форм
        double term1 = 1.0;
        double term2 = x / 2.0;
        double term3 = (x * x) / (2.0 * 4.0);
        double term4 = (3.0 * x * x * x) / (2.0 * 4.0 * 6.0);
        double term5 = (3.0 * 5.0 * x * x * x * x) / (2.0 * 4.0 * 6.0 * 8.0);
        double f_approx_direct = term1 + term2 - term3 + term4 - term5;

        // г) Абсолютная и относительная ошибки (для скобочной формы)
        double abs_error = fabs(f_exact - f_approx_bracket);
        double rel_error = abs_error / f_exact;

        // Вывод строки таблицы
        printf("%-10.6f | %-12.8f | %-15.8f | %-15.8f | %-12.4e | %-12.4e\n", 
               x, f_exact, f_approx_bracket, f_approx_direct, abs_error, rel_error);
    }
    
    printf("=================================================================================================================\n");

    return 0;
}
